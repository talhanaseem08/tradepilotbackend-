"""
Generates finetuned bot Python files from tuned parameters.

Rules:
- Original bot files are NEVER modified.
- Each tuning run produces a new file in app/bots/finetuned/.
- Generated class inherits from the original bot class and injects tuned defaults.
- Backtesting files for original bots are untouched.
"""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from app.utils.logger import get_logger

logger = get_logger()

FINETUNED_DIR = Path(__file__).parent.parent / "bots" / "finetuned"

# Maps bot_type -> (import_module, ClassName)
_BOT_TYPE_MAP: dict[str, tuple[str, str]] = {
    "low_risk":      ("app.bots.low_risk_orb_bot",   "LowRiskOrbBot"),
    "medium_risk":   ("app.bots.medium_risk_bos_bot", "MediumRiskBosBot"),
    "high_risk":     ("app.bots.high_risk_orb_bot",   "HighRiskOrbBot"),
    "crypto_low":    ("app.bots.crypto_low_bot",      "CryptoLowBot"),
    "crypto_medium": ("app.bots.crypto_medium_bot",   "CryptoMediumBot"),
    "crypto_high":   ("app.bots.crypto_high_bot",     "CryptoHighBot"),
}


def _sanitize_reasoning(text: str) -> str:
    """Escape triple-quotes so reasoning embeds safely in a comment."""
    return text.replace('"""', "'''")[:500]


def _params_repr(params: dict, indent: int = 12) -> str:
    """Render dict entries as Python literal lines, each at `indent` spaces."""
    pad = " " * indent
    lines = []
    for k, v in params.items():
        if isinstance(v, str):
            lines.append(f'{pad}"{k}": "{v}",')
        else:
            lines.append(f"{pad}{k!r}: {v!r},")
    return "\n".join(lines)


def write_finetuned_bot(
    bot_type: str,
    bot_id: str,
    final_params: dict,
    reasoning: str,
    consecutive_losses: int,
) -> str:
    """
    Write a finetuned bot Python file.

    Returns the absolute path of the generated file.
    Raises ValueError if bot_type is unknown.
    """
    if bot_type not in _BOT_TYPE_MAP:
        raise ValueError(f"Unknown bot_type '{bot_type}'. Known: {list(_BOT_TYPE_MAP)}")

    module_path, base_class = _BOT_TYPE_MAP[bot_type]
    ts = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")
    class_name = f"{base_class}Finetuned{ts}"
    file_name = f"{bot_type}_finetuned_{ts}.py"
    file_path = FINETUNED_DIR / file_name

    safe_reasoning = _sanitize_reasoning(reasoning)
    params_block = _params_repr(final_params, indent=12)
    generated_at = datetime.now(timezone.utc).isoformat()

    lines = [
        "# AUTO-GENERATED by TradePilot Agent Service - DO NOT EDIT MANUALLY",
        f"# Source bot  : {bot_type} ({base_class})",
        f"# Bot ID      : {bot_id}",
        f"# Generated at: {generated_at}",
        f"# Trigger     : {consecutive_losses} consecutive losses",
        f"# Reasoning   : {safe_reasoning}",
        "from __future__ import annotations",
        "",
        f"from {module_path} import {base_class}",
        "",
        "",
        f"class {class_name}({base_class}):",
        f'    """Finetuned variant of {base_class} - auto-generated, do not edit."""',
        "",
        "    FINETUNED: bool = True",
        f'    SOURCE_BOT_TYPE: str = "{bot_type}"',
        f'    BOT_ID: str = "{bot_id}"',
        f'    FINETUNED_AT: str = "{generated_at}"',
        "",
        "    def __init__(self, symbol: str, timeframe: str, parameters: dict) -> None:",
        "        tuned: dict = {",
        params_block,
        "        }",
        "        tuned.update(parameters)",
        "        super().__init__(symbol, timeframe, tuned)",
        "",
    ]
    source = "\n".join(lines)

    FINETUNED_DIR.mkdir(parents=True, exist_ok=True)
    file_path.write_text(source, encoding="utf-8")

    logger.info(
        "finetuned bot written",
        bot_type=bot_type,
        bot_id=bot_id,
        file=str(file_path),
        class_name=class_name,
    )
    return str(file_path)
